// Writes src/app/fonts.generated.css. The Caractères files are yours (they are not in this repo), so they are
// only referenced when they exist in public/fonts. Without them the page uses an installed copy if there is one
// (local), then Big Shoulders / IBM Plex Mono, and never makes a request that would 404.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const has = (f) => existsSync(new URL(`../public/fonts/${f}`, import.meta.url));
const face = (family, locals, files, weight = '100 900') => {
  const src = [
    ...locals.map((l) => `local('${l}')`),
    ...files.filter(([f]) => has(f)).map(([f, fmt]) => `url('/fonts/${f}') format('${fmt}')`),
  ].join(', ');
  return `@font-face { font-family: '${family}'; src: ${src}; font-weight: ${weight}; font-display: swap; }`;
};

// The symbols Caractères lacks or draws as something else ($ % & are road-sign units there), drawn by scripts/symbols.py.
const range = has('symbols.ranges.txt') ? readFileSync(new URL('../public/fonts/symbols.ranges.txt', import.meta.url), 'utf8').trim() : '';
const symbols = (k) => has(`PMCSymbols${k}.woff2`)
  ? `@font-face { font-family: 'PMC Symbols ${k}'; src: url('/fonts/PMCSymbols${k}.woff2') format('woff2'); unicode-range: ${range}; font-display: swap; }`
  : '';

const css = `/* GENERATED by scripts/fonts.mjs. Do not edit. */
@font-face { font-family: 'Shoulders'; src: url('/fonts/BigShouldersDisplay-900.woff2') format('woff2'); font-weight: 100 900; font-display: swap; }
@font-face { font-family: 'Plex'; src: url('/fonts/IBMPlexMono-400.woff2') format('woff2'); font-weight: 400; font-display: swap; }
${symbols('L2')}
${symbols('L4')}
${face('Caracteres L2', ['Caracteres L2', 'Caractères L2'], [['CaracteresL2.woff2', 'woff2'], ['CaracteresL2.ttf', 'truetype']])}
${face('Caracteres L4', ['Caracteres L4', 'Caractères L4'], [['CaracteresL4.woff2', 'woff2'], ['CaracteresL4.ttf', 'truetype']])}
@font-face { font-family: 'JetBrains Mono'; src: url('/fonts/JetBrainsMono-Regular.woff2') format('woff2'); font-weight: 400; font-display: swap; }
@font-face { font-family: 'JetBrains Mono'; src: url('/fonts/JetBrainsMono-Bold.woff2') format('woff2'); font-weight: 700; font-display: swap; }
`;
writeFileSync(new URL('../src/app/fonts.generated.css', import.meta.url), css);
console.log('Fonts: Caracteres L2 ' + (has('CaracteresL2.woff2') || has('CaracteresL2.ttf') ? 'found' : 'not in public/fonts (using fallback)') + ', L4 ' + (has('CaracteresL4.woff2') || has('CaracteresL4.ttf') ? 'found' : 'not in public/fonts (using fallback)'));
